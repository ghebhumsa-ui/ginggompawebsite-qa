function setSiteLanguage(language) {
    const selectedLanguage = siteTranslations[language] ? language : "en";

    const languageCodes = {
        en: "en",
        ne: "ne",
        hi: "hi",
        bo: "bo"
    };

    document.documentElement.lang = languageCodes[selectedLanguage] || "en";

    document.querySelectorAll("[data-i18n]").forEach(function(element) {
        const key = element.getAttribute("data-i18n");

        if (!element.dataset.i18nDefault) {
            element.dataset.i18nDefault = element.innerHTML;
        }

        const translatedText = siteTranslations[selectedLanguage] && siteTranslations[selectedLanguage][key];
        element.innerHTML = translatedText || element.dataset.i18nDefault;
    });

    document.querySelectorAll("[data-lang-option]").forEach(function(button) {
        const isActive = button.getAttribute("data-lang-option") === selectedLanguage;
        button.classList.toggle("active", isActive);
        button.setAttribute("aria-pressed", String(isActive));
    });

    document.querySelectorAll("[data-language-note]").forEach(function(note) {
        note.hidden = note.getAttribute("data-language-note") !== selectedLanguage;
    });

    localStorage.setItem("gingGompaLanguage", selectedLanguage);
}

document.addEventListener("DOMContentLoaded", function() {
    const savedLanguage = localStorage.getItem("gingGompaLanguage") || "en";
    setSiteLanguage(savedLanguage);

    document.querySelectorAll("[data-lang-option]").forEach(function(button) {
        button.addEventListener("click", function() {
            setSiteLanguage(button.getAttribute("data-lang-option"));
        });
    });
});
